#!/usr/bin/env python3
"""Single source of the headline numbers used in README, docs/DEMO.md and the deck.
(Not named numbers.py: that would shadow the stdlib `numbers` module for every script in scripts/.)

Reads raw run files in results/ (git-ignored, present on the dev machine) and the generated
EXPERIMENTS.md (for bootstrap CIs) and writes docs/numbers.json. Docs mark every headline
number as <span data-n="KEY">VALUE</span>; tests/test_numbers.py asserts VALUE == numbers.json.

Usage: python scripts/pitch_numbers.py [--check]   (--check: exit 1 if docs/numbers.json is stale)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
OUT = ROOT / "docs" / "numbers.json"
SPAN_RE = re.compile(r'<span data-n="([a-z0-9_]+)">([^<]*)</span>')

# Keys that must appear (marked) in each pitch document.
REQUIRED = {
    "README.md": ["jury_heldout", "cascade_heldout", "dev_mean", "jury_usd", "cascade_usd",
                  "local_cascade_heldout", "dev_agreement"],
    "docs/DEMO.md": ["jury_heldout", "cascade_heldout", "dev_mean", "jury_usd", "cascade_usd",
                     "local_cascade_heldout"],
    "docs/presentation.html": ["jury_heldout", "cascade_heldout", "dev_mean", "jury_usd", "cascade_usd",
                               "local_cascade_heldout", "dev_agreement"],
}


def _load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def fmt_acc(x: float) -> str:
    s = f"{x:.3f}"
    return s[:-1] if s.endswith("0") else s


def fmt_usd(x: float) -> str:
    """Three significant digits: 0.158, 0.0146, 0.00128."""
    return "$" + f"{x:.3g}"


def exp_row(text: str, name_fragment: str) -> tuple[float, float, float, str | None]:
    """(acc, lo, hi, usd) from the EXPERIMENTS.md master leaderboard row containing name_fragment."""
    for line in text.splitlines():
        if line.startswith("|") and name_fragment in line:
            m = re.search(r"\| (\d\.\d{3}) \[(\d\.\d{3}), (\d\.\d{3})\] \|", line)
            if m:
                u = re.search(r"\| \$([\d.]+) \|", line)
                return float(m[1]), float(m[2]), float(m[3]), (u[1] if u else None)
    raise SystemExit(f"EXPERIMENTS.md: leaderboard row '{name_fragment}' not found")


def build() -> dict:
    exp = (ROOT / "EXPERIMENTS.md").read_text(encoding="utf-8")
    jury_acc, jury_lo, jury_hi, _ = exp_row(exp, "| jury-haiku+sonnet>opus |")
    casc_acc_x, casc_lo, casc_hi, _ = exp_row(exp, "preset `cascade`")

    casc_h = _load(R / "oss" / "jev3_holdout.json")
    casc_acc = casc_h["metrics"]["overall_agreement"]
    assert abs(casc_acc - casc_acc_x) < 1e-9, (casc_acc, casc_acc_x)

    # DEV mean = latest full run (v8: 07 closure_mode + 02 examples, = results/dev/results.json);
    # $/dialog = v7, the last run measured without a warm criterion cache (v8 reused cached verdicts).
    dev = _load(R / "dev_jury_v8.json")
    totals = [d["total"] for d in dev["dialogs"] if d.get("total") is not None]
    n_dev = len(dev["dialogs"])
    cost_run = _load(R / "dev_jury_v7.json")
    jury_usd = cost_run["meta"]["cost_usd"] / len(cost_run["dialogs"])

    casc_d = _load(R / "oss" / "jev3_dev.json")
    jev_usd = _load(R / "jev" / "holdout.json")["usd_per_dialog"]
    casc_usd = casc_d["routing"]["cloud_usd"] / casc_d["dialogs"] + jev_usd
    dev_agree = casc_d["vs_cloud"]["overall_exact"]

    loc = _load(R / "kz_models" / "cascade-vllm-choice__Qwen_Qwen3.8-27B-FP8.json")

    raw = {
        "jury_heldout": jury_acc,
        "jury_heldout_ci": [jury_lo, jury_hi],
        "cascade_heldout": casc_acc,
        "cascade_heldout_ci": [casc_lo, casc_hi],
        "heldout_n": 10,
        "dev_n": n_dev,
        "dev_mean": round(sum(totals) / len(totals), 2),
        "dev_agreement": dev_agree,
        "jury_usd": jury_usd,
        "cascade_usd": casc_usd,
        "cost_ratio": jury_usd / casc_usd,
        "local_cascade_heldout": loc["overall_agreement"],
        "local_cascade_usd": loc["usd_per_dialog"],
        "local_cascade_model": loc["model"],
    }
    display = {
        "jury_heldout": fmt_acc(jury_acc),
        "jury_heldout_ci": f"[{jury_lo:.3f}, {jury_hi:.3f}]",
        "cascade_heldout": fmt_acc(casc_acc),
        "cascade_heldout_ci": f"[{casc_lo:.3f}, {casc_hi:.3f}]",
        "heldout_n": "10",
        "dev_n": str(n_dev),
        "dev_mean": f"{raw['dev_mean']:.2f}",
        "dev_agreement": fmt_acc(dev_agree),
        "jury_usd": fmt_usd(jury_usd),
        "cascade_usd": fmt_usd(casc_usd),
        "cost_ratio": f"{round(jury_usd / casc_usd)}×",
        "local_cascade_heldout": fmt_acc(loc["overall_agreement"]),
        "local_cascade_usd": fmt_usd(loc["usd_per_dialog"]),
    }
    return {
        "_doc": "Generated by scripts/pitch_numbers.py from results/* and EXPERIMENTS.md. Do not edit by hand. "
                "$/dialog = DEV (65 real dialogs). held-out = 10 synthetic dialogs, 95% bootstrap CI.",
        "raw": raw,
        "display": display,
    }


def main() -> int:
    data = build()
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/numbers.json is stale: run python scripts/pitch_numbers.py")
            return 1
        print("numbers OK")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(json.dumps(data["display"], ensure_ascii=False, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
